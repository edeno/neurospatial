@pytest.mark.realdata
def test_loads_default_session(session_entry, assert_default_session):
    """The survey's session: 49 units, 45 trials, 2,118 ripples, the 90 cm disc."""
    rec = load("huszar_2026")
    assert_default_session(rec, session_entry("huszar_2026"))
    assert rec.n_units == 49
    assert rec.units["brain_region"].value_counts().to_dict() == {"CA1": 26, "CA3": 23}
    assert rec.times.size == 236_084
    assert rec.sampling_rate == pytest.approx(29.985, rel=1e-3)
    assert float(np.mean(~np.isfinite(rec.positions).all(axis=1))) == pytest.approx(
        0.0530, abs=1e-4
    )
    assert len(rec.trials) == 45
    assert rec.events["ripples"].shape == (2118, 2)
    assert rec.events["rewards"].shape == (90,)
    assert rec.epochs["on_maze"].shape == (52, 2)
    np.testing.assert_allclose(rec.env.regions["reward_1"].data, [44.5711, 74.2334])
    order = next(c for c in rec.conversions if "rewardOrder k" in c.text)
    assert "a median 2.34 cm from the well its rewardOrder names" in order.evidence


