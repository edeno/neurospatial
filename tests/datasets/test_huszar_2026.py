"""Huszár et al. (2026), DANDI 001880: synthetic NWB files and the real session."""

from __future__ import annotations

import datetime

import numpy as np
import pytest

from neurospatial.datasets import load
from neurospatial.datasets._checks import run_checks

#: The platform's centre in the synthetic camera frame, cm.
CENTRE = np.array([46.0, 45.0])
WELLS = np.array([[44.0, 74.0], [63.0, 35.0]])
#: Sub-sessions (PRE, Learning, POST), s; rest in the home cage between them.
SUB = ((60.0, 660.0), (1000.0, 1600.0), (2000.0, 2600.0))
#: The three learning trials, s: (box open, LED on maze, rewards, rewardOrder,
#: stop); the third finds one reward only.
TRIALS = (
    (1080.0, 1100.0, (1150.0, 1200.0), (2, 1), 1250.0),
    (1260.0, 1270.0, (1330.0, 1380.0), (1, 2), 1400.0),
    (1410.0, 1420.0, (1450.0, np.nan), (1, 0), 1500.0),
)
#: The maze visits (onMaze): one in PRE, one per trial, one in POST, s.
MAZE = ((100.0, 600.0), *((on, stop) for _, on, _, _, stop in TRIALS), (2100.0, 2500.0))


def _positions(times, *, held=True, glitch=False):
    """A path over the disc on the maze; a held fix at the edge off it.

    ``held=False`` keeps the path moving off the maze; ``glitch`` puts 30
    on-maze samples 300 cm off, as a tracking glitch does.
    """
    phase = 2 * np.pi * times / 37.0
    radius = 40.0 * np.abs(np.sin(times / 11.0))
    xy = CENTRE + radius[:, None] * np.column_stack([np.cos(phase), np.sin(phase)])
    on = np.zeros(times.size, dtype=bool)
    for start, stop in MAZE:
        on |= (times >= start) & (times < stop)
    if held:
        xy[~on] = CENTRE + np.array([44.0, 0.0])  # the tracker's last fix, by the box
    if glitch:
        first = int(np.flatnonzero(on)[1000])
        xy[first : first + 30] = CENTRE + np.array([300.0, 0.0])
    for _, _, rewards, orders, _ in TRIALS:  # at each well when rewarded
        for when, k in zip(rewards, orders, strict=True):
            if k:
                xy[np.abs(times - when) < 0.5] = WELLS[k - 1]
    return xy


def _intervals(name, description, rows, **columns):
    from pynwb.epoch import TimeIntervals

    table = TimeIntervals(name=name, description=description)
    for column in columns:
        table.add_column(column, column)
    for index, (start, stop) in enumerate(rows):
        table.add_interval(
            start_time=float(start),
            stop_time=float(stop),
            **{key: values[index] for key, values in columns.items()},
        )
    return table


def _write_session(
    path,
    *,
    unit="cm",
    zero_length_state=False,
    held=True,
    glitch=False,
    trials=TRIALS,
):
    """An NWB file laid out as DANDI 001880's, at 30 Hz, cm, one LED."""
    pynwb = pytest.importorskip("pynwb")
    from hdmf.common import DynamicTable, VectorData
    from pynwb.behavior import Position, SpatialSeries
    from pynwb.file import Subject

    nwb = pynwb.NWBFile(
        "Auto-generated by neuroconv",
        "synthetic",
        datetime.datetime(2022, 12, 8, tzinfo=datetime.timezone.utc),
        subject=Subject(subject_id="iuvE14_x", species="Mus musculus"),
    )
    times = np.concatenate([np.arange(a, b, 1 / 30) for a, b in SUB])
    xy = _positions(times, held=held, glitch=glitch)
    behavior = nwb.create_processing_module("behavior", "behavior")
    position = Position(name="SubjectPosition")
    position.add_spatial_series(
        SpatialSeries(
            name="PositionSeries",
            description="(x,y) coordinates tracking subject movement.",
            data=xy,
            timestamps=times,
            reference_frame="Arbitrary, camera",
            unit=unit,
        )
    )
    position.add_spatial_series(
        SpatialSeries(
            name="VelocitySeries",
            description="(vx,vy,v) coordinates tracking subject movement.",
            data=np.zeros((times.size, 3)),
            timestamps=times,
            reference_frame="Arbitrary, camera",
            unit="cm/s",
        )
    )
    behavior.add(position)
    labels = ("PRE", "Learning", "POST")
    maze_rows = list(MAZE)
    maze_labels = ["PRE", *["Learning"] * len(TRIALS), "POST"]
    box_rows = [(MAZE[0][0] - 20.0, MAZE[0][1])]
    box_rows += [(box, stop) for (box, _, _, _, stop) in TRIALS]
    box_rows += [(MAZE[-1][0] - 20.0, MAZE[-1][1])]
    behavior.add(
        _intervals(
            "onMaze",
            "Intevals when LED was detected on a maze",
            maze_rows,
            subSession=maze_labels,
        )
    )
    behavior.add(
        _intervals(
            "openBox",
            "Intevals when the box was open",
            box_rows,
            subSession=maze_labels,
        )
    )
    behavior.add(_intervals("subSessions", "subSessions", SUB, label=list(labels)))
    states = [(1.0, 800.0, "Awake"), (801.0, 900.0, "Non-REM"), (901.0, 950.0, "REM")]
    states += [(951.0, 2700.0, "Awake")]
    if zero_length_state:
        states += [(2700.0, 2700.0, "Awake")]
    behavior.add(
        _intervals(
            "SleepStates",
            "Sleep state of the animal.",
            [row[:2] for row in states],
            label=[row[2] for row in states],
        )
    )
    behavior.add(
        _intervals(
            "LearningTrials",
            "Learning trials and rewards information",
            [(box, stop) for (box, _, _, _, stop) in trials],
            onMaze_start_time=[on for (_, on, _, _, _) in trials],
            rewardTime=[list(rewards) for (_, _, rewards, _, _) in trials],
            rewardOrder=[list(orders) for (_, _, _, orders, _) in trials],
        )
    )
    behavior.add(
        DynamicTable(
            name="rewardCoordinates",
            description="(x,y) coordinates of rewards",
            columns=[
                VectorData(name="x", description="X coordinate", data=WELLS[:, 0]),
                VectorData(name="y", description="Y coordinate", data=WELLS[:, 1]),
            ],
        )
    )
    ripples = [(150.0, 150.05), (700.0, 700.04), (1450.0, 1450.03)]
    nwb.create_processing_module("ecephys", "ecephys").add(
        _intervals(
            "Ripples",
            "Ripples and their metrics",
            ripples,
            peaks=[start + 0.01 for start, _ in ripples],
        )
    )
    nwb.add_acquisition(
        _intervals(
            "pulses",
            "Pulses intervals and sites",
            [(2650.0, 2650.002), (2690.0, 2690.002)],
        )
    )
    nwb.add_unit_column("location", "Brain region where the unit was detected")
    nwb.add_unit_column("cell_type", "Putative cell type of a unit")
    nwb.add_unit_column("CA1_optoTag", "Whether a unit was optoTagged as CA1")
    rng = np.random.default_rng(0)
    for location, cell_type, tag in (
        ("CA1", "Pyramidal Cell", 1),
        ("CA3", "Narrow Interneuron", 0),
    ):
        nwb.add_unit(
            spike_times=np.sort(rng.uniform(0.5, 2699.0, 500)),
            location=location,
            cell_type=cell_type,
            CA1_optoTag=tag,
        )
    with pynwb.NWBHDF5IO(str(path), "w") as io:
        io.write(nwb)
    return times, xy


