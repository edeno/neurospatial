"""Laps counted by ``detect_laps`` against laps counted from the path itself.

On a circular track the number of laps is known without ``detect_laps``: the
angle of the position around the track's centre turns once per lap, and the
file's linearized coordinate wraps once per lap. This script reports both,
next to ``detect_laps`` on an environment built from the samples, with its
defaults and with two other settings.

Writes ``results/studies/lap_truth.{md,json}``. Run:
``uv run --group datasets --extra nwb python datasets/studies/lap_truth.py``.
"""

from __future__ import annotations

import importlib
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from run import LOADERS  # noqa: E402

RESULTS = HERE.parent / "results" / "studies"
DATASETS = ("grosmark_000044_circular",)
SETTINGS: dict[str, dict[str, Any]] = {
    "defaults": {},
    "min_overlap=0.5": {"min_overlap": 0.5},
    "max_gap=None": {"max_gap": None},
}


def path_laps(positions: np.ndarray, linearized: np.ndarray) -> dict[str, float]:
    """Turns around the median position and wraps of the linearized coordinate."""
    tracked = np.isfinite(positions).all(axis=1)
    centre = np.median(positions[tracked], axis=0)
    angle = np.unwrap(
        np.arctan2(positions[tracked, 1] - centre[1], positions[tracked, 0] - centre[0])
    )
    on_track = linearized[np.isfinite(linearized)]
    length = float(on_track.max())
    return {
        "net_turns": float((angle[-1] - angle[0]) / (2 * np.pi)),
        "total_turns": float(np.sum(np.abs(np.diff(angle))) / (2 * np.pi)),
        "linearized_wraps": int(np.sum(np.abs(np.diff(on_track)) > length / 2)),
        "untracked_share": float(1 - tracked.mean()),
    }


def run(keys: tuple[str, ...]) -> list[dict[str, Any]]:
    from neurospatial import Environment
    from neurospatial.behavior import detect_laps

    rows = []
    for key in keys:
        rec = importlib.import_module(LOADERS[key]).load()
        env = Environment.from_samples(
            rec.positions, bin_size=rec.params["bin_size"], units=rec.position_units
        )
        row: dict[str, Any] = {
            "dataset": key,
            **path_laps(rec.positions, rec.params["linearized"]),
        }
        tracked_times = rec.times[np.isfinite(rec.positions).all(axis=1)]
        row["tracked_gaps_over_1s"] = int(np.sum(np.diff(tracked_times) > 1.0))
        for name, kwargs in SETTINGS.items():
            row[f"detect_laps {name}"] = len(
                detect_laps(env, rec.times, rec.positions, **kwargs)
            )
        rows.append(row)
        print(row, flush=True)
    return rows


def render(rows: list[dict[str, Any]]) -> str:
    keys = [k for k in rows[0] if k != "dataset"]
    lines = [
        "# Laps from the path against `detect_laps`",
        "",
        "Generated by `datasets/studies/lap_truth.py`; see its docstring.",
        "",
        "| dataset | " + " | ".join(keys) + " |",
        "| --- | " + " | ".join("---" for _ in keys) + " |",
    ]
    lines.extend(
        f"| {row['dataset']} | "
        + " | ".join(
            f"{row[k]:.3g}" if isinstance(row[k], float) else str(row[k]) for k in keys
        )
        + " |"
        for row in rows
    )
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    rows = run(tuple(sys.argv[1:]) or DATASETS)
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "lap_truth.json").write_text(json.dumps(rows, indent=2) + "\n")
    (RESULTS / "lap_truth.md").write_text(render(rows))
