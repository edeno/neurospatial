"""Numbers behind the proposed warnings, on every clean recording.

For each loader in ``run.LOADERS`` (correctly loaded data, no defects put
back):

- **Origin share**: the share of tracked samples exactly at the origin, for
  the positions the loader returns and, where the loader keeps one in
  ``params["linearized"]``, for the linearized coordinate. The proposed
  warning fires at ``ORIGIN_SHARE`` or more.
- **Fewest bins**: the fewest bins along any dimension of
  ``Environment.from_samples`` at the loader's ``bin_size``. The proposed
  warning fires below ``MIN_BINS``.
- **Heading coverage**: of ``N_DIRECTION_BINS`` direction bins, how many hold
  at least ``MIN_BIN_SHARE`` of the samples, over all samples and over running
  samples (faster than ``RUNNING_CM_S``). The proposed warning fires below
  half the bins.

Writes ``results/studies/warning_calibration.{md,json}``. Run:
``uv run --group datasets --extra nwb python datasets/studies/warning_calibration.py``.
"""

from __future__ import annotations

import importlib
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from _record import Recording  # noqa: E402
from run import LOADERS  # noqa: E402

RESULTS = HERE.parent / "results" / "studies"
ORIGIN_SHARE = 0.001
MIN_BINS = 5
N_DIRECTION_BINS = 36
MIN_BIN_SHARE = 0.005
RUNNING_CM_S = 10.0


def origin_share(values: np.ndarray) -> float:
    """Share of finite samples with every coordinate exactly 0."""
    values = np.asarray(values, dtype=float).reshape(len(values), -1)
    tracked = np.isfinite(values).all(axis=1)
    return (
        float(np.mean((values[tracked] == 0).all(axis=1)))
        if tracked.any()
        else float("nan")
    )


def fewest_bins(rec: Recording) -> int:
    from neurospatial import Environment

    units = None if rec.position_units == "arbitrary" else rec.position_units
    env = Environment.from_samples(
        rec.positions, bin_size=rec.params["bin_size"], units=units
    )
    return int(min(env.grid_shape))


def heading_coverage(headings: np.ndarray) -> int:
    """Direction bins holding at least ``MIN_BIN_SHARE`` of the finite samples."""
    finite = headings[np.isfinite(headings)]
    counts, _ = np.histogram(
        np.mod(finite + np.pi, 2 * np.pi), bins=N_DIRECTION_BINS, range=(0, 2 * np.pi)
    )
    return int(np.sum(counts >= MIN_BIN_SHARE * finite.size))


def running(rec: Recording) -> np.ndarray:
    step = np.linalg.norm(np.diff(rec.positions, axis=0), axis=1) / np.diff(rec.times)
    return np.append(step > RUNNING_CM_S, False)


def summarize(rec: Recording) -> dict[str, Any]:
    row: dict[str, Any] = {"dataset": rec.dataset}
    if rec.positions is not None:
        row["origin_share"] = origin_share(rec.positions)
        row["fewest_bins"] = fewest_bins(rec)
    if "linearized" in rec.params:
        row["linearized_origin_share"] = origin_share(rec.params["linearized"])
    if rec.headings is not None:
        row["heading_bins"] = heading_coverage(rec.headings)
        if rec.positions is not None and rec.position_units == "cm":
            row["heading_bins_running"] = heading_coverage(rec.headings[running(rec)])
    return row


def render(rows: list[dict[str, Any]]) -> str:
    def cell(row: dict[str, Any], key: str, fmt: str) -> str:
        return format(row[key], fmt) if key in row else "–"

    lines = [
        "# Warning calibration on clean recordings",
        "",
        "Generated by `datasets/studies/warning_calibration.py`; see its docstring.",
        f" Origin share fires at {ORIGIN_SHARE:.1%} or more; fewest bins below {MIN_BINS};"
        f" heading coverage below {N_DIRECTION_BINS // 2} of {N_DIRECTION_BINS} bins"
        f" (a bin counts at {MIN_BIN_SHARE:.1%} of samples).",
        "",
        "| Dataset | Origin share | Linearized origin share | Fewest bins | Heading bins | Heading bins, running |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    lines.extend(
        f"| {row['dataset']} | {cell(row, 'origin_share', '.3%')} |"
        f" {cell(row, 'linearized_origin_share', '.3%')} | {cell(row, 'fewest_bins', 'd')} |"
        f" {cell(row, 'heading_bins', 'd')} | {cell(row, 'heading_bins_running', 'd')} |"
        for row in rows
    )
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    keys = sys.argv[1:] or list(LOADERS)
    rows = []
    for key in keys:
        rows.append(summarize(importlib.import_module(LOADERS[key]).load()))
        print(rows[-1], flush=True)
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "warning_calibration.json").write_text(json.dumps(rows, indent=2) + "\n")
    (RESULTS / "warning_calibration.md").write_text(render(rows))
