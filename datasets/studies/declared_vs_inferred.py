"""What changes when the driver analyses the declared apparatus instead of the samples' grid?

Reads each dataset's results twice: ``results/<key>.json`` (the run that uses
the loader's declared environment) and ``results/inferred_env/<key>.json``
(``run.py --inferred-env``: every environment built from the samples). For
each dataset with a declared environment, it tabulates the summaries that
depend on the environment: bins, occupancy, spatial information, place
screen, decoding error and its chance level, laps (default and by start
region), turns and replay detection rates, with each cell's status when it is
not ``ok``. Decoding error is the median geodesic error along each run's own
environment (the declared track, or the samples' grid); "the declared
track's samples" restricts both runs to the time bins whose true position
the declared environment places, so the two are medians over the same
samples.

Writes ``results/studies/declared_vs_inferred.md``. Run after both driver
runs: ``uv run --group datasets python datasets/studies/declared_vs_inferred.py``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parent / "results"
OUT = RESULTS / "studies" / "declared_vs_inferred.md"

# (operation, summary key, label, format)
MEASURES: tuple[tuple[str, str, str, str], ...] = (
    ("env.declared", "frac_samples_outside", "samples outside", ".1%"),
    ("env.occupancy", "total_s", "occupancy (s)", ".0f"),
    ("env.occupancy", "frac_bins_visited", "bins visited", ".0%"),
    ("rates.spatial", "frac_nan_bins", "NaN rate bins", ".1%"),
    ("rates.spatial_information", "bits_per_spike_median", "info (bits/spike)", ".3f"),
    ("rates.information_vs_shifts", "frac_above_every_shift", "above shifts", ".0%"),
    ("cells.place_screen", "n_place_screen", "place screen", "d"),
    (
        "decode.position",
        "median_error",
        "decode error (each run's placed samples)",
        ".1f",
    ),
    (
        "decode.position",
        "median_error_on_declared",
        "decode error (time bins both environments place)",
        ".1f",
    ),
    ("decode.position", "frac_actual_outside", "true positions outside", ".1%"),
    ("decode.position", "chance_median_error", "chance error", ".1f"),
    ("behavior.laps", "n_laps", "laps (default)", "d"),
    ("behavior.laps", "n_laps_region", "laps (region)", "d"),
    ("behavior.turn_sequence", "n_turns", "turns", "d"),
    ("replay.compare_methods", "davidson_2009_rate", "Davidson rate", ".3f"),
    ("replay.compare_methods", "grosmark_2016_rate", "Grosmark rate", ".3f"),
)


def cell(entry: dict[str, Any] | None, key: str, spec: str) -> str:
    """One value, or the cell's status when the operation did not run cleanly."""
    if entry is None:
        return ""
    status = entry.get("status")
    value = (entry.get("summary") or {}).get(key)
    if status in ("error", "missing", "n/a"):
        return "–" if status == "n/a" else status
    if value is None:
        return ""
    text = format(value, spec) if isinstance(value, int | float) else str(value)
    return text if status == "ok" else f"{text} ({status})"


def rows_for(
    declared: dict[str, Any], inferred: dict[str, Any]
) -> list[tuple[str, str, str]]:
    """(label, declared value, inferred value) for each measure either run has."""
    rows = []
    first_key = {}
    for op, key, _, _ in MEASURES:
        first_key.setdefault(op, key)
    for op, key, label, spec in MEASURES:
        entries = [run["operations"].get(op) or {} for run in (declared, inferred)]
        has_key = any(key in (entry.get("summary") or {}) for entry in entries)
        # A failed operation is shown once, on its first measure.
        if not has_key and key != first_key[op]:
            continue
        a, b = (cell(entry or None, key, spec) for entry in entries)
        if a or b:
            rows.append((label, a, b))
    a = declared["operations"].get("env.declared", {}).get("summary", {}).get("n_bins")
    b = (
        inferred["operations"]
        .get("env.from_samples", {})
        .get("summary", {})
        .get("n_bins")
    )
    rows.insert(0, ("bins", "" if a is None else str(a), "" if b is None else str(b)))
    return rows


def render(pairs: list[tuple[dict[str, Any], dict[str, Any]]]) -> str:
    lines = [
        "# Declared against inferred environments",
        "",
        "Generated by `datasets/studies/declared_vs_inferred.py`. Per dataset:"
        " the run on the loader's declared environment against the run on the"
        " samples-built one (`run.py --inferred-env`). A cell shows the status"
        " instead of a value when the operation did not run (`–` n/a); a"
        " workaround is marked.",
        "",
    ]
    for declared, inferred in pairs:
        lines += [
            f"## {declared['dataset']}",
            "",
            "| measure | declared | inferred |",
            "| --- | --- | --- |",
        ]
        lines += [f"| {a} | {b} | {c} |" for a, b, c in rows_for(declared, inferred)]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> None:
    keys = argv or sorted(p.stem for p in (RESULTS / "inferred_env").glob("*.json"))
    pairs = []
    for key in keys:
        declared = json.loads((RESULTS / f"{key}.json").read_text())
        if declared.get("env_kind") != "declared":
            continue
        inferred = json.loads((RESULTS / "inferred_env" / f"{key}.json").read_text())
        pairs.append((declared, inferred))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(pairs))


if __name__ == "__main__":
    main(sys.argv[1:])
