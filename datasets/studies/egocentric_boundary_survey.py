"""Egocentric boundary maps on every recording with head direction.

Runs the ``rates.egocentric_boundary`` operation (``operations.egocentric_boundary``:
``compute_boundary_vector_rates`` with ``direction_frame="egocentric"`` and
``boundary_source="analysis"``, defaults otherwise) on each loader in
``run.LOADERS`` whose recording has 2-D positions, head direction and spikes,
without rewriting the driver's results files. Per recording it reports the
number of units, the median preferred distance, the share of units whose peak
lies in the outermost ring (where untuned cells peak by chance, the
function's docstring says), the share peaking on the left, the median
distance information, the warnings emitted and the runtime.

Writes ``results/studies/egocentric_boundary.{md,json}``. Run:
``uv run --group datasets --extra nwb --extra pynapple python
datasets/studies/egocentric_boundary_survey.py [KEY ...]``.
"""

from __future__ import annotations

import importlib
import json
import sys
import time
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from _calibration import captured  # noqa: E402
from operations import egocentric_boundary  # noqa: E402
from run import LOADERS  # noqa: E402

RESULTS = HERE.parent / "results" / "studies"


def survey(key: str) -> dict[str, Any]:
    """Run the operation on one recording, or say which input it lacks."""
    rec = importlib.import_module(LOADERS[key]).load()
    missing = [
        name
        for name in ("positions", "headings", "spike_times")
        if getattr(rec, name) is None
    ]
    if missing:
        return {"dataset": key, "skipped": f"needs {', '.join(missing)}"}
    start = time.perf_counter()
    outcome, error, warnings = captured(egocentric_boundary, rec, {})
    row: dict[str, Any] = {
        "dataset": key,
        "seconds": round(time.perf_counter() - start, 1),
        "warnings": [w["example"] for w in warnings],
    }
    if error is not None:
        row["error"] = f"{type(error).__name__}: {error}"
    else:
        row["status"] = outcome.status
        row.update(outcome.summary)
    return row


def render(rows: list[dict[str, Any]]) -> str:
    lines = [
        "# Egocentric boundary maps",
        "",
        "Generated by `datasets/studies/egocentric_boundary_survey.py`; see its"
        " docstring. Defaults: 0-50 cm in 5 cm rings, 30 degree sectors,"
        " unsmoothed; walls are the edge of the visited bins.",
        "",
        "| Dataset | Units | Median preferred distance | Peak in the last ring"
        " | Peak on the left | Median distance information | Warnings | Note |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        if "n_units" not in row:
            note = row.get("skipped") or row.get("error") or row.get("status", "")
            lines.append(f"| {row['dataset']} | | | | | | | {note} |")
            continue
        lines.append(
            f"| {row['dataset']} | {row['n_units']} |"
            f" {row['median_preferred_distance']:.1f} |"
            f" {row['frac_peak_in_last_ring']:.0%} | {row['frac_peak_on_left']:.0%} |"
            f" {row.get('distance_information_median', float('nan')):.3f} |"
            f" {len(row['warnings'])} | {row['status']} |"
        )
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    keys = sys.argv[1:] or list(LOADERS)
    rows = []
    for key in keys:
        rows.append(survey(key))
        print({k: v for k, v in rows[-1].items() if k != "warnings"}, flush=True)
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "egocentric_boundary.json").write_text(
        json.dumps(rows, indent=2, default=str) + "\n"
    )
    (RESULTS / "egocentric_boundary.md").write_text(render(rows))
